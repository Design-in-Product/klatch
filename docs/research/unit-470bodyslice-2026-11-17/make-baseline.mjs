#!/usr/bin/env node
/**
 * Writes `scripts/decl-body-slicers.baseline` from a RECORDED detector drive, not from a live
 * re-scan — so the list the gate grandfathers is exactly the population a committed artefact
 * reports, and a reviewer can diff one against the other.
 *
 * Usage: node make-baseline.mjs <detector-drive-output> <baseline-path>
 *
 * Deliberately a separate script rather than a `--write-baseline` flag on the detector: a gate that
 * can rewrite its own baseline can always be made green by running it, which is not a gate.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const [, , drivePath, baselinePath] = process.argv;
if (!drivePath || !baselinePath) {
  console.error('usage: make-baseline.mjs <detector-drive-output> <baseline-path>');
  process.exit(2);
}
const lines = readFileSync(resolve(process.cwd(), drivePath), 'utf8').split('\n');
const start = lines.findIndex((l) => l.startsWith('RED — ') && l.includes('new hand-rolled'));
if (start === -1) { console.error('no "RED — … new hand-rolled" section in that drive'); process.exit(2); }
const paths = [];
for (const l of lines.slice(start + 1)) {
  const m = /^ {6}(\S+)$/.exec(l);
  if (!m) break; // the indented run of paths ends at the first non-matching line
  paths.push(m[1]);
}
paths.sort();
const header = [
  '# Known hand-rolled brace-balance body slicers in the TRACKED tree — the population that',
  '# predates `scripts/lib/decl-body.mjs` and is grandfathered by',
  '# `scripts/verify-decl-body-slicers.mjs`.',
  '#',
  '# Generated by `docs/research/unit-470bodyslice-2026-11-17/make-baseline.mjs` from the recorded',
  `# drive it was given, NOT from a live re-scan. Source drive: ${drivePath}`,
  '#',
  '# These are overwhelmingly one-off research arms whose figures are already published, which is',
  '# why they are grandfathered rather than migrated (RESULTS §2). Six of them are the files the',
  '# unit-469braceslice census called GUARDED: they paren-match the parameter list but do NOT',
  '# handle a brace-bearing return type, which is live at 16 sites in packages/ (RESULTS §4). They',
  '# are listed here as unguarded under the stricter key, deliberately.',
  '#',
  '# An entry that stops qualifying REDDENS the detector: remove it rather than leaving a dead',
  '# exemption nobody can tell from a live one.',
  '',
].join('\n');
writeFileSync(resolve(process.cwd(), baselinePath), `${header}${paths.join('\n')}\n`);
console.log(`wrote ${paths.length} entries to ${baselinePath}`);
