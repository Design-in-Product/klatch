// unit-464grep — build `lifted-reader.mjs` by SLICING the reader out of unit-464rec's census
// at a LITERAL rev, not by retyping it.
//
// Retyping a reader is the defect this track has already paid for twice: a hand-typed reader is
// not a slice, and the typed copy diverges from the thing whose behaviour you are claiming to
// reuse. So the lift is a byte slice between two structural anchors, the source rev is a literal
// (not `log -1 -- <path>`, which is exactly the recency-keyed selector this unit is about), and
// the slice is gated three ways before it is written.

import { execFileSync } from 'node:child_process';
import { writeFileSync, readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';

const HERE = dirname(new URL(import.meta.url).pathname);
const REPO = resolve(HERE, '../../..');

// LITERAL, not derived. `2c084be8` is the rev at which the reader below was last written.
// If the phrase/anchors stop matching at this rev the lift REFUSES rather than guessing.
const SRC_REV = '2c084be8';
const SRC_PATH = 'docs/research/unit-464rec-2026-10-31/rec-census.mjs';

const START = '// ---------------------------------------------------------------- lexer';
const END = 'const HEX = /^[0-9a-f]{7,40}$/;';

const src = execFileSync('git', ['-C', REPO, 'show', `${SRC_REV}:${SRC_PATH}`], {
  encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 * 1024 * 1024,
});

// G-LIFT-1: each anchor occurs EXACTLY once. "Sliced exactly once" does not pin the start
// anchor unless both ends are counted, so both are counted.
const countOf = (needle) => src.split(needle).length - 1;
const nStart = countOf(START);
const nEnd = countOf(END);
const iStart = src.indexOf(START);
const iEnd = src.indexOf(END);

console.log(`source       ${SRC_REV}:${SRC_PATH}`);
console.log(`source bytes ${Buffer.byteLength(src, 'utf8')} (Buffer.byteLength)`);
console.log(`G-LIFT-1 ${nStart === 1 && nEnd === 1 ? 'ok ' : 'RED'} start anchor x${nStart}, end anchor x${nEnd} (both must be 1)`);
console.log(`G-LIFT-2 ${iStart >= 0 && iEnd > iStart ? 'ok ' : 'RED'} start at ${iStart}, end at ${iEnd} (end must follow start)`);

if (!(nStart === 1 && nEnd === 1 && iStart >= 0 && iEnd > iStart)) {
  console.log('REFUSED: the anchors do not pin a single span at this rev. No file written.');
  process.exit(2);
}

const slice = src.slice(iStart, iEnd);

// G-LIFT-3: the span must actually contain every symbol the consumer imports. A present
// anchor does not mean an intact span, so the members are asserted by name.
const WANT = ['function lex(', 'function callSpans(', 'function gitness(', 'function argvWords(', 'function constMap('];
const missing = WANT.filter((w) => !slice.includes(w));
console.log(`G-LIFT-3 ${missing.length === 0 ? 'ok ' : 'RED'} ${WANT.length - missing.length} of ${WANT.length} expected members present${missing.length ? ` — MISSING: ${missing.join(', ')}` : ''}`);
if (missing.length) { console.log('REFUSED: slice is not intact. No file written.'); process.exit(2); }

const header = `// GENERATED BY lift-reader.mjs — DO NOT EDIT BY HAND.
//
// A byte slice of ${SRC_PATH}
// at rev ${SRC_REV}, between the anchors:
//   start: ${JSON.stringify(START)}
//   end:   ${JSON.stringify(END)}
// Rebuild with: node lift-reader.mjs
//
// Nothing below this header was typed by hand. The \`export\` line at the foot is the only
// addition, and it adds no behaviour.

`;
const footer = `
export { lex, callSpans, gitness, argvWords, constMap };
`;

const out = header + slice + footer;
const outPath = `${HERE}/lifted-reader.mjs`;
writeFileSync(outPath, out);

const sliceHash = createHash('sha256').update(slice, 'utf8').digest('hex').slice(0, 16);
console.log(`slice bytes  ${Buffer.byteLength(slice, 'utf8')} · sha256/16 ${sliceHash}`);

// G-LIFT-4: round-trip. Read the written file back off DISK and assert the slice survives it
// verbatim — guard the published artefact, not the string that went into it.
const back = readFileSync(outPath, 'utf8');
const roundTrip = back.includes(slice) && Buffer.byteLength(back, 'utf8') === Buffer.byteLength(out, 'utf8');
console.log(`G-LIFT-4 ${roundTrip ? 'ok ' : 'RED'} written file re-read from disk contains the slice verbatim`);

console.log('');
console.log(`LIFTVERDICT/${roundTrip ? 0 : 1}  ${roundTrip ? 'all four lift gates ok' : 'see the RED line above'}`);
process.exit(roundTrip ? 0 : 1);
