#!/usr/bin/env node
/**
 * unit-496guardkeyreach — the GUARD's key versus the HAZARD's key.
 *
 * Subject: assertion (c) in `scripts/verify-decl-body-slicers.mjs` — the line-ending guard built by
 * Daedalus in `unit-495lineendingguard` (2026-11-21 START) on this seat's word. His §7 invites a
 * second reading of his §2's two sites. This is that reading, plus the question his cripple's key
 * could not ask: `publish()` refuses on `line.endsWith(LABEL)`, while the hazard it names is
 * `/LABEL\s+(\d+)/` whose `\s+` crosses a newline. Those two keys are not the same key.
 *
 * brace-slicer-deliberate: this file slices named spans out of the gate's own source by anchor and
 * byte range in order to drive the REAL `publish()`; it does no brace-balance body slicing of its
 * own and compares against no braces, so it is out of the gate's population either way.
 *
 * Every plant lives inside this unit's harness. The real gate is never edited: yesterday's two-seat
 * decision closed format edits to published instruments, and `unit-492`'s ceiling says the two live
 * instruments are not cold yet.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync, spawnSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = execFileSync('git', ['-C', HERE, 'rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim();
const GATE = join(ROOT, 'scripts/verify-decl-body-slicers.mjs');
const SRC = readFileSync(GATE, 'utf8');
const out = [];
const say = (s = '') => { out.push(s); };

/* ---------------------------------------------------------------- slice, do not re-type (lesson) */
// A hand-typed reader is not a slice. Each span is pinned on BOTH a start and an end anchor, each
// anchor asserted to occur exactly once, and the extracted text asserted byte-identical to
// `SRC.slice(start, end)` — `sliced exactly once` alone does not pin the start anchor.
function sliceSpan(name, startAnchor, endAnchor) {
  const s = SRC.indexOf(startAnchor);
  if (s < 0 || SRC.indexOf(startAnchor, s + 1) >= 0) {
    throw new Error(`span ${name}: start anchor is not unique (${s})`);
  }
  const e = SRC.indexOf(endAnchor, s);
  if (e < 0 || SRC.indexOf(endAnchor, e + 1) >= 0) {
    throw new Error(`span ${name}: end anchor is not unique (${e})`);
  }
  const end = e + endAnchor.length;
  const text = SRC.slice(s, end);
  if (text !== SRC.substring(s, end)) throw new Error(`span ${name}: slice is not the source`);
  const line = SRC.slice(0, s).split('\n').length;
  return { name, text, line, bytes: Buffer.byteLength(text, 'utf8') };
}

const spans = [
  sliceSpan('LABELS', "const LABELS = ['MARKED'", "'UNGUARDED'];"),
  sliceSpan('refuse', 'function refuse(message) {', "  process.exit(2);\n}"),
  sliceSpan('publish', 'function publish(sink, args) {', '  sink(chunk);\n}'),
];
say('=== unit-496 arm: the guard key vs the hazard key, over the REAL sliced publish() ===');
say('spans extracted verbatim from the gate source (byte-identical to the file, not re-typed):');
for (const s of spans) say(`  ${s.name.padEnd(8)} gate line ${String(s.line).padStart(3)}  ${s.bytes} B`);
say('');

/* ----------------------------------------------------------------------------- the harness module */
const CASES = [
  ['kp-bare', '  scripts/lib/decl-body.mjs  → GUARDED', 2, 'P1 KP: bare label last must refuse'],
  ['padded-one-space', '  scripts/lib/decl-body.mjs  → GUARDED ', 0, 'P2: one trailing space'],
  ['padded-two-spaces', '  scripts/lib/decl-body.mjs  → GUARDED  ', 0, 'P2: two trailing spaces'],
  ['padded-tab', '  scripts/lib/decl-body.mjs  → GUARDED\t', 0, 'P2: trailing tab'],
  ['control-quoted', '  scripts/lib/decl-body.mjs  → `GUARDED`', 0, 'control: his cure, must publish'],
  ['absent-terminal', '  scripts/lib/decl-body.mjs  → now ABSENT', 0, 'his C5c declared limit'],
  ['padded-then-count', '  scripts/lib/decl-body.mjs  → GUARDED \n  12  members', 0, 'P3 fusion subject'],
  ['bare-then-count', '  scripts/lib/decl-body.mjs  → GUARDED\n  12  members', 2, 'P3 counterfactual'],
];

const harnessPath = join(HERE, 'harness-sliced-publish.mjs');
const harness = `// GENERATED by probe-guard-key-reach.mjs — spans below are byte-identical slices of
// scripts/verify-decl-body-slicers.mjs. Do not edit; re-run the probe.
import { format } from 'node:util';
${spans.map((s) => s.text).join('\n')}
const emit = (...args) => publish((c) => console.log(c), args);
const CASES = ${JSON.stringify(Object.fromEntries(CASES.map(([k, v]) => [k, v])))};
const payload = CASES[process.argv[2]];
if (payload === undefined) { console.error('no such case'); process.exit(3); }
emit(payload);
process.exit(0);
`;
mkdirSync(HERE, { recursive: true });
writeFileSync(harnessPath, harness);

/* --------------------------------------------------------------------------------- P1, P2, drives */
say('--- drives: one child process per case, against the sliced real publish() ---');
say('  case                   rc  published?  stdout B  stderr B  endsWith(label)  refused');
const results = {};
for (const [name, payload, , note] of CASES) {
  const r = spawnSync('node', [harnessPath, name], { encoding: 'utf8' });
  const lines = payload.split('\n');
  const LABELS_LIVE = ['MARKED', 'GUARDED', 'UNGUARDED'];
  const endsWithLabel = lines.filter((l) => LABELS_LIVE.some((v) => l.endsWith(v))).length;
  const refused = /BLOCKED/.test(r.stderr);
  results[name] = {
    rc: r.status, stdout: r.stdout, stderr: r.stderr, published: r.stdout.length > 0, refused, note,
  };
  say(`  ${name.padEnd(20)} ${String(r.status).padStart(3)}  ${String(r.stdout.length > 0).padEnd(10)}`
    + `  ${String(Buffer.byteLength(r.stdout, 'utf8')).padStart(8)}  ${String(Buffer.byteLength(r.stderr, 'utf8')).padStart(8)}`
    + `  ${String(endsWithLabel).padStart(15)}  ${refused}`);
}
say('');

/* ------------------------------------------------------------------------------ P3: does it fuse? */
// The hazard's own reader, from `unit-486markerstale` §5 and quoted in the gate's docblock.
const FUSE = /GUARDED\s+(\d+)/;
say('--- P3: the hazard reader over each form, and whether the match crosses a newline ---');
say('  form                    guard verdict   /GUARDED\\s+(\\d+)/ returns   crosses newline');
const fuseRows = [];
for (const form of ['padded-then-count', 'bare-then-count']) {
  const payload = CASES.find(([n]) => n === form)[1];
  // Read the hazard over the TEXT in both cases — the bare form cannot be published at all, which
  // is the point: the guard distinguishes them, the hazard's reader does not.
  const m = FUSE.exec(payload);
  const crosses = m ? m[0].includes('\n') : false;
  fuseRows.push({ form, digit: m ? m[1] : null, crosses, guard: results[form].refused ? 'REFUSED' : 'published' });
  say(`  ${form.padEnd(22)}  ${(results[form].refused ? 'REFUSED' : 'published').padEnd(13)}`
    + `   ${String(m ? m[1] : 'no match').padEnd(24)}  ${crosses}`);
}
// And over what was actually PUBLISHED by the padded case, not over my own string.
const pubPadded = results['padded-then-count'].stdout;
const mPub = FUSE.exec(pubPadded);
say(`  over the padded case's ACTUAL published bytes: ${mPub ? `returns ${mPub[1]}, crosses=${mPub[0].includes('\n')}` : 'no match'}`);
say('');

/* ------------------------------- P4: reach of the padded form in the live subject's real output */
const fresh = spawnSync('node', [join(ROOT, 'scripts/verify-decl-body-slicers.mjs')], { encoding: 'utf8', cwd: ROOT });
writeFileSync(join(HERE, 'drive1.gate-fresh.out'), fresh.stdout);
const freshLines = fresh.stdout.split('\n');
const trailingWs = freshLines.map((l, i) => [i + 1, l]).filter(([, l]) => l.length > 0 && /\s$/.test(l));
say('--- P4: the live gate\'s own published output ---');
say(`  gate rc=${fresh.status} · stdout ${Buffer.byteLength(fresh.stdout, 'utf8')} BYTES`
  + ` (${fresh.stdout.length} chars — the two differ, and the difference is D1) · ${freshLines.length} lines`);
say(`  published lines ending in whitespace: ${trailingWs.length}`);
for (const [n, l] of trailingWs.slice(0, 6)) say(`      line ${n}: ${JSON.stringify(l.slice(-40))}`);
const labelTerminalLive = freshLines.filter((l) => ['MARKED', 'GUARDED', 'UNGUARDED'].some((v) => l.endsWith(v)));
say(`  published lines ending in a bare verdict label: ${labelTerminalLive.length}  (conjunct (i) today)`);
// KP for that zero: the same reader over a synthetic line that must report 1.
const kpReader = ['  x  → GUARDED'].filter((l) => ['MARKED', 'GUARDED', 'UNGUARDED'].some((v) => l.endsWith(v)));
say(`  KP for the two zeros above (same reader, synthetic line that must report 1): ${kpReader.length}`);
say('');

/* ----------------- P5: independent census of emit sites that can render a label LAST */
// Key derived from what the mechanism can produce, not from what today's tree happens to print: a
// published line can only BECOME label-terminal without a source edit if its template ends in an
// interpolation. Those are the only candidate sites; every other line ends in literal text.
say('--- P5: every emit/emitErr whose template ends in an interpolation (dynamic last token) ---');
const callRe = /\b(emitErr|emit)\(([\s\S]*?)\);\n/g;
const sites = [];
let m2;
while ((m2 = callRe.exec(SRC)) !== null) {
  const line = SRC.slice(0, m2.index).split('\n').length;
  const argText = m2[2];
  sites.push({ fn: m2[1], line, argText });
}
const dynamicLast = sites.filter((s) => /\$\{[^}]*\}`\s*$/.test(s.argText.trim())
  || /\$\{[^}]*\}`\s*\+?\s*$/.test(s.argText.trim()));
say(`  emit/emitErr call sites found: ${sites.length}  (emit ${sites.filter((s) => s.fn === 'emit').length}`
  + ` · emitErr ${sites.filter((s) => s.fn === 'emitErr').length})`);
say(`  of those, template ends in an interpolation: ${dynamicLast.length}`);
for (const s of dynamicLast) {
  const tail = s.argText.trim().split('\n').pop().trim();
  const holdsLabel = /verdicts|LABELS|\bv\b|counts/.test(tail);
  say(`      gate line ${String(s.line).padStart(3)}  ${s.fn.padEnd(7)} can-hold-a-label=${holdsLabel}  ${tail.slice(-72)}`);
}
say('');

/* --------------------- P6: the stderr surface — direct console.* calls that bypass publish() */
say('--- P6: direct console.* writes in the gate, which do NOT route through publish() ---');
const conRe = /console\.(log|error)\(/g;
const cons = [];
let m3;
while ((m3 = conRe.exec(SRC)) !== null) {
  const line = SRC.slice(0, m3.index).split('\n').length;
  const inPublish = spans.some((s) => {
    const start = SRC.indexOf(s.text);
    return m3.index >= start && m3.index < start + s.text.length;
  });
  cons.push({ line, stream: m3[1], inPublish });
}
const bypass = cons.filter((c) => !c.inPublish);
say(`  console.* call sites in the gate: ${cons.length}`);
say(`  inside the sliced refuse()/publish()/emit wiring: ${cons.filter((c) => c.inPublish).length}`);
say(`  BYPASSING publish() entirely: ${bypass.length}  → lines ${bypass.map((c) => c.line).join(', ')}`);
// Are any of those bypass messages label-terminal? Read each call's literal text from source.
let bypassLabelTerminal = 0;
for (const c of bypass) {
  const from = SRC.split('\n').slice(c.line - 1, c.line + 6).join('\n');
  const stmt = from.slice(0, from.indexOf(');') + 2);
  const literals = [...stmt.matchAll(/`([^`]*)`/g)].map((x) => x[1]);
  const last = literals.length ? literals[literals.length - 1] : '';
  const term = ['MARKED', 'GUARDED', 'UNGUARDED'].some((v) => last.trimEnd().endsWith(v));
  if (term) bypassLabelTerminal += 1;
}
say(`  of the bypassing sites, label-terminal in their own literal text: ${bypassLabelTerminal}`);
say('');
say('=== end unit-496 arm ===');

const text = `${out.join('\n')}\n`;
process.stdout.write(text);
