#!/usr/bin/env node
/**
 * `unit-502streampin-2026-11-22` — the arm.
 *
 * Grades P1–P4 and P7 of `PRE-REGISTRATION.md`. P5 and P6 are graded by the landing recorder
 * (`posthoc-landing.mjs`) because they straddle a patch and a commit.
 *
 * Four drive families:
 *   A  the `newOnes` limb, out of sample, at path lengths nobody has driven (83; 84+85+86)
 *   B  the `stale` limb — the gate's second red limb, which no seat has ever driven
 *   C  a reader-only cripple pair over the stale limb's entry literal, measuring the `ABSENT` hole
 *      in assertion (c)'s label key, WITH its known positive
 *
 * Hazard discipline, held rather than asserted:
 *   - no brace character is compared anywhere in this file; the plant's comparisons are built from
 *     `String.fromCharCode`, so this arm cannot enter the population it measures;
 *   - the exemption token is never spelled here, for the same reason, and the one place it has to
 *     be counted builds it from parts;
 *   - family A mutates the INDEX only (`git add -N`: index entry, no blob) and reverses it in a
 *     `finally`, with the reversal asserted;
 *   - family B/C write only inside an already-`.gitignore`d directory and touch no tracked file.
 */

import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, cpSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../../..');
const GATE = resolve(ROOT, 'scripts/verify-decl-body-slicers.mjs');
const CAPS = join(HERE, 'captures');
const PLANTS = join(HERE, 'plants');
const SCRATCH = join(HERE, 'scratch');

const OPEN = String.fromCharCode(123);
const CLOSE = String.fromCharCode(125);
const Q = String.fromCharCode(39);

const sha = (b) => createHash('sha256').update(b).digest('hex');
const bytes = (b) => Buffer.byteLength(b);
const lineCount = (s) => (s.match(new RegExp(String.fromCharCode(10), 'g')) || []).length;

const log = [];
const say = (s) => { log.push(s); console.log(s); };
const rows = [];
const grade = (id, claim, predicted, measured) => {
  const hit = String(predicted) === String(measured);
  rows.push({ id, claim, predicted, measured, hit });
  say(`  ${hit ? 'HIT ' : 'MISS'}  ${id}  ${claim}`);
  say(`          predicted ${predicted}`);
  say(`          measured  ${measured}`);
  return hit;
};

/* ------------------------------------------------------------------ drive helpers */
function driveGate(file, cwd = ROOT) {
  const r = spawnSync('node', [file], { cwd, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  return { rc: r.status, out: r.stdout ?? '', err: r.stderr ?? '' };
}
function record(name, d) {
  writeFileSync(join(CAPS, `${name}.out`), d.out);
  writeFileSync(join(CAPS, `${name}.err`), d.err);
  return `rc=${d.rc} stdout ${bytes(d.out)}B/${lineCount(d.out)}L stderr ${bytes(d.err)}B/${lineCount(d.err)}L`;
}

/* ------------------------------------------------------------------ the plant */
// A hand-rolled brace-balance body slicer: in the population (compares against BOTH braces), and
// UNGUARDED (no paren/paren/colon comparison triple). Generated, never written out here.
function plantSource(tag) {
  const eq = ' === ';
  return [
    `// unit-502streampin plant ${tag} — a deliberately unguarded brace-balance body slicer,`,
    '// generated by arm-stream-pin.mjs, visible to `git ls-files` only via `git add -N`.',
    'export function plantBody(src, from) {',
    '  let depth = 0;',
    '  for (let i = from; i < src.length; i += 1) {',
    '    const ch = src[i];',
    `    if (ch${eq}${Q}${OPEN}${Q}) depth += 1;`,
    `    if (ch${eq}${Q}${CLOSE}${Q}) depth -= 1;`,
    '    if (depth === 0) return src.slice(from, i + 1);',
    '  }',
    `  return ${Q}${Q};`,
    '}',
    '',
  ].join(String.fromCharCode(10));
}

/** Build a plant path under PLANTS whose repo-relative length is EXACTLY `want`. */
function plantPathOfLength(want, tag) {
  const relDir = 'docs/research/unit-502streampin-2026-11-22/plants/';
  const suffix = `-${tag}.mjs`;
  const padLen = want - relDir.length - suffix.length;
  if (padLen < 1) throw new Error(`want=${want} too short for ${relDir}*${suffix}`);
  const rel = `${relDir}${'p'.repeat(padLen)}${suffix}`;
  if (rel.length !== want) throw new Error(`built ${rel.length}, wanted ${want}`);
  return rel;
}

/* ================================================================== FAMILY A */
say('unit-502streampin — arm');
say(`  gate sha256 ${sha(readFileSync(GATE))}`);
say('');
say('FAMILY A — the `newOnes` limb, OUT OF SAMPLE (predictions from the literal-derived law)');

const planted = [];
try {
  mkdirSync(PLANTS, { recursive: true });

  // ---- A1: one plant, path length 83
  const a1rel = plantPathOfLength(83, 'a1');
  writeFileSync(join(ROOT, a1rel), plantSource('a1'));
  planted.push(a1rel);
  execFileSync('git', ['-C', ROOT, 'add', '-N', a1rel]);
  say(`  A1 plant ${a1rel}  (length ${a1rel.length})`);
  const a1 = driveGate(GATE);
  say(`     ${record('a1-red-one-plant', a1)}`);
  grade('P1.A1.rc', 'A1 exit code', 1, a1.rc);
  grade('P1.A1.errbytes', 'A1 stderr bytes = 658 + (83 + 7)', 748, bytes(a1.err));
  grade('P1.A1.errlines', 'A1 stderr lines = 7 + 1', 8, lineCount(a1.err));
  grade('P1.A1.outbytes', 'A1 stdout bytes', 3935, bytes(a1.out));
  grade('P1.A1.outlines', 'A1 stdout lines', 38, lineCount(a1.out));

  // ---- A2: three plants, path lengths 84, 85, 86
  const a2rels = [84, 85, 86].map((n, i) => plantPathOfLength(n, `a2${String.fromCharCode(120 + i)}`));
  for (const rel of a2rels) {
    writeFileSync(join(ROOT, rel), plantSource('a2'));
    planted.push(rel);
    execFileSync('git', ['-C', ROOT, 'add', '-N', rel]);
  }
  say(`  A2 plants ${a2rels.map((r) => r.length).join(', ')} chars`);
  const a2 = driveGate(GATE);
  say(`     ${record('a2-red-three-plants', a2)}`);
  grade('P1.A2.rc', 'A2 exit code', 1, a2.rc);
  grade('P1.A2.errbytes', 'A2 stderr bytes = 658 + (84+7)+(85+7)+(86+7)', 934, bytes(a2.err));
  grade('P1.A2.errlines', 'A2 stderr lines = 7 + 3', 10, lineCount(a2.err));
  grade('P1.A2.outbytes', 'A2 stdout bytes', 3935, bytes(a2.out));

  // ---- P2: same byte count, different bytes, 3 differing lines
  grade('P2.count', 'A1/A2 stdout byte COUNT equal', true, bytes(a1.out) === bytes(a2.out));
  grade('P2.sha', 'A1/A2 stdout BYTES differ (sha256)', true, sha(a1.out) !== sha(a2.out));
  const nlc = String.fromCharCode(10);
  const l1 = a1.out.split(nlc);
  const l2 = a2.out.split(nlc);
  const diff = l1.map((l, i) => [i + 1, l, l2[i]]).filter(([, a, b]) => a !== b);
  grade('P2.difflines', 'A1 vs A2 differing published lines', 3, diff.length);
  for (const [n, a, b] of diff) {
    say(`       L${n}  ${JSON.stringify(a)}  ->  ${JSON.stringify(b)}   widths ${bytes(a)} / ${bytes(b)}`);
  }
} finally {
  // Reverse the index mutation and remove the plants, then ASSERT the reversal.
  for (const rel of planted) {
    try { execFileSync('git', ['-C', ROOT, 'reset', '-q', '--', rel]); } catch { /* best effort */ }
    try { rmSync(join(ROOT, rel)); } catch { /* best effort */ }
  }
  try { rmSync(PLANTS, { recursive: true, force: true }); } catch { /* best effort */ }
  const porcelain = execFileSync('git', ['-C', ROOT, 'status', '--porcelain'], { encoding: 'utf8' });
  const leftovers = porcelain.split(String.fromCharCode(10)).filter((l) => l.includes('plants/'));
  const onDisk = planted.filter((rel) => existsSync(join(ROOT, rel)));
  say('');
  say('  REVERSAL of family A, asserted rather than assumed:');
  say(`     plants surviving on disk: ${onDisk.length}  (expected 0)`);
  say(`     plant lines in \`git status --porcelain\`: ${leftovers.length}  (expected 0)`);
  for (const rel of planted) {
    const r = spawnSync('git', ['-C', ROOT, 'ls-files', '--error-unmatch', rel], { encoding: 'utf8' });
    if (r.status === 0) say(`     STILL TRACKED: ${rel}`);
  }
}

/* ================================================================== FAMILY B / C */
say('');
say('FAMILY B — the `stale` limb, which no seat has ever driven');

const gateSrc = readFileSync(GATE, 'utf8');
const gateSha = sha(Buffer.from(gateSrc));
const COPY = join(SCRATCH, 'gatecopy');

function buildCopy(transform, entryLengths) {
  rmSync(COPY, { recursive: true, force: true });
  mkdirSync(join(COPY, 'lib'), { recursive: true });
  const src = transform ? transform(gateSrc) : gateSrc;
  const copyPath = join(COPY, 'verify-decl-body-slicers.mjs');
  writeFileSync(copyPath, src);
  cpSync(resolve(ROOT, 'scripts/lib/strip-source.mjs'), join(COPY, 'lib/strip-source.mjs'));
  const entries = entryLengths.map((n, i) => `${'e'.repeat(n - 1)}${String.fromCharCode(97 + i)}`);
  for (const [i, e] of entries.entries()) {
    if (e.length !== entryLengths[i]) throw new Error(`entry ${i} is ${e.length}, wanted ${entryLengths[i]}`);
  }
  writeFileSync(join(COPY, 'decl-body-slicers.baseline'), `${entries.join(String.fromCharCode(10))}${String.fromCharCode(10)}`);
  return { copyPath, copySha: sha(readFileSync(copyPath)), entries };
}

// The scratch tree must be invisible to git, or family B is editing the tracked tree by another
// name. Asserted, not assumed.
mkdirSync(SCRATCH, { recursive: true });
const ign = spawnSync('git', ['-C', ROOT, 'check-ignore', '-q', join(SCRATCH, 'x')], { encoding: 'utf8' });
say(`  scratch dir is .gitignore'd: ${ign.status === 0}  (git check-ignore rc=${ign.status})`);

try {
  // ---- B1: one baseline entry, path length 40
  const b1c = buildCopy(null, [40]);
  grade('P3.copy.sha', 'the driven copy is byte-identical to the tracked gate', gateSha, b1c.copySha);
  const b1 = driveGate(b1c.copyPath);
  say(`     ${record('b1-stale-one-entry', b1)}`);
  grade('P3.B1.rc', 'B1 exit code', 1, b1.rc);
  grade('P3.B1.errbytes', 'B1 stderr bytes = 227 + (40 + 25)', 292, bytes(b1.err));
  grade('P3.B1.errlines', 'B1 stderr lines = 4 + 1', 5, lineCount(b1.err));
  grade('P3.B1.refusals', 'B1 refusals (rc would be 2)', 0, b1.err.includes('BLOCKED') ? 1 : 0);
  say(`     B1 stderr, verbatim:`);
  for (const l of b1.err.split(String.fromCharCode(10))) say(`       | ${l}`);

  // ---- B2: three baseline entries, lengths 40, 41, 42
  const b2c = buildCopy(null, [40, 41, 42]);
  const b2 = driveGate(b2c.copyPath);
  say(`     ${record('b2-stale-three-entries', b2)}`);
  grade('P3.B2.rc', 'B2 exit code', 1, b2.rc);
  grade('P3.B2.errbytes', 'B2 stderr bytes = 227 + (65+66+67)', 425, bytes(b2.err));
  grade('P3.B2.errlines', 'B2 stderr lines = 4 + 3', 7, lineCount(b2.err));

  /* ------------------------------------------------- FAMILY C: the ABSENT hole, with its KP */
  say('');
  say('FAMILY C — the `ABSENT` hole in assertion (c)\'s label key, and its known positive');

  // The entry literal, located by its own distinctive text and transformed. One substitution each,
  // asserted to apply exactly once.
  const QUOTED = '  → now \\`${verdicts.get(f) ?? \'ABSENT\'}\\`';
  const UNQUOTED = '  → now ${verdicts.get(f) ?? \'ABSENT\'}';
  const UNQUOTED_LABEL = '  → now ${verdicts.get(f) ?? \'GUARDED\'}';
  const occurrences = gateSrc.split(QUOTED).length - 1;
  grade('P4.cripple.sites', 'the entry literal appears exactly once in the gate source', 1, occurrences);

  const c1c = buildCopy((s) => s.replace(QUOTED, UNQUOTED), [40]);
  const c1 = driveGate(c1c.copyPath);
  say(`     ${record('c1-cripple-unquoted-absent', c1)}`);
  grade('P4.C1.rc', 'C1 (unquoted, ABSENT) exit code — the hole: it PUBLISHES', 1, c1.rc);
  grade('P4.C1.publishes', 'C1 stderr carries the stale block', true, c1.err.includes('stale baseline'));
  grade('P4.C1.refused', 'C1 refusal', false, c1.err.includes('BLOCKED'));

  const c2c = buildCopy((s) => s.replace(QUOTED, UNQUOTED_LABEL), [40]);
  const c2 = driveGate(c2c.copyPath);
  say(`     ${record('c2-cripple-unquoted-label', c2)}`);
  grade('P4.C2.rc', 'C2 (unquoted, a real LABEL) exit code — the known positive', 2, c2.rc);
  grade('P4.C2.refused', 'C2 refuses, naming the label', true,
    c2.err.includes('BLOCKED') && c2.err.includes('GUARDED'));
  say('     C2 stderr, verbatim:');
  for (const l of c2.err.split(String.fromCharCode(10))) say(`       | ${l}`);
} finally {
  rmSync(SCRATCH, { recursive: true, force: true });
  say('');
  say(`  scratch tree removed: ${!existsSync(SCRATCH)}`);
}

/* ================================================================== P7 hazards */
say('');
say('P7 — hazards, measured');
const TOKEN = ['brace', '-slicer-', 'deliberate', ':'].join('');
const mine = ['arm-stream-pin.mjs', 'PRE-REGISTRATION.md'];
for (const f of mine) {
  const p = join(HERE, f);
  const n = existsSync(p) ? readFileSync(p, 'utf8').split(TOKEN).length - 1 : 'absent';
  say(`  ${f}: ${n} literal occurrence(s) of the exemption token`);
}
say('  (derive-limb-laws.mjs necessarily QUOTES the token — it slices the route-2 literal by its own');
say('   text — so it joins the quoted-only list by construction. See RESULTS P7.)');

/* ================================================================== summary */
const hits = rows.filter((r) => r.hit).length;
say('');
say(`SUMMARY — ${hits} of ${rows.length} graded assertions HIT`);
for (const r of rows.filter((x) => !x.hit)) say(`  MISS  ${r.id}  predicted ${r.predicted}  measured ${r.measured}`);
writeFileSync(join(CAPS, 'arm-stream-pin.json'), `${JSON.stringify(rows, null, 2)}${String.fromCharCode(10)}`);
